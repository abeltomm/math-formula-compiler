#!/usr/bin/env python3
"""Automated test runner: runs every case through the REAL C compiler.

    python tests/test_runner.py

Prints a result table and writes docs/test_results.md. Exit code is 0 only if
every test passes. A test passes only when the result, the failing stage AND the
pipeline integrity (no stage after a failed stage reports 'passed') all match.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "ui"))
from compiler_bridge import run_compiler, CompilerError  # noqa: E402

STAGE_FOR = {"Lexical": "Lexical Analysis", "Syntax": "Syntax Analysis", "Semantic": "Semantic Analysis"}


def rows(filename):
    with open(os.path.join(HERE, filename), encoding="utf-8") as fh:
        for line in fh:
            if line.strip() and not line.lstrip().startswith("#"):
                yield [c.strip() for c in line.rstrip("\n").split("|")]


def pipeline_ok(rep):
    """After the first failed stage, every later stage must be skipped or failed - never 'passed'."""
    failed = False
    for st in rep["stages"]:
        if failed and st["status"] == "passed":
            return False
        if st["status"] == "failed":
            failed = True
    return True


def run_valid():
    out = []
    for formula, expected in rows("valid_tests.txt"):
        formula = formula.replace("\\n", "\n")
        rep = run_compiler(formula)
        actual = rep["ast_sexpr"] if rep["status"] == "success" else "FAILED: " + rep["errors"][0]["message"]
        ok = rep["status"] == "success" and actual == expected and pipeline_ok(rep)
        stage = "All stages passed" if rep["status"] == "success" else rep["failed_stage"]
        out.append((formula, "Compiles; AST " + expected, actual, stage, ok))
    return out


def run_invalid():
    out = []
    for cat, formula, fragment in rows("invalid_tests.txt"):
        rep = run_compiler(formula)
        expected_stage = STAGE_FOR[cat]
        if rep["status"] == "failed" and rep["errors"]:
            e = rep["errors"][0]
            actual = "%s error %d:%d: %s" % (e["category"], e["line"], e["col"], e["message"])
            ok = (rep["failed_stage"] == expected_stage and e["category"] == cat
                  and fragment in e["message"] and pipeline_ok(rep))
        else:
            actual, ok = "Compiled successfully (wrong)", False
        out.append((formula, "%s error containing \"%s\"" % (cat, fragment), actual, rep.get("failed_stage") or "none", ok))
    return out


def run_eval():
    out = []
    for formula, variables, expected in rows("eval_tests.txt"):
        rep = run_compiler(formula, evaluate=True, variables=variables)
        ev = rep["evaluation"]
        if not rep["status"] == "success" or not ev["performed"]:
            actual, ok = "did not evaluate", False
        elif ev["ok"]:
            actual = "%.10g" % ev["value"]
            ok = not expected.startswith("error:") and abs(ev["value"] - float(expected)) < 1e-9
        else:
            actual = "error: " + ev["message"]
            ok = expected.startswith("error:") and expected[6:].strip().lower() in ev["message"].lower()
        label = formula + ("   [" + variables + "]" if variables else "")
        out.append((label, expected, actual, "Evaluation (runtime)", ok))
    return out


def md_table(title, results):
    lines = ["### " + title, "", "| # | Input formula | Expected result | Actual result | Stage involved | Status |",
             "|---|---|---|---|---|---|"]
    for i, (f, e, a, s, ok) in enumerate(results, 1):
        cell = lambda t: t.replace("|", "\\|").replace("\n", "\\n")
        lines.append("| %d | `%s` | %s | %s | %s | %s |" % (i, cell(f), cell(e), cell(a), s, "PASS" if ok else "FAIL"))
    return "\n".join(lines) + "\n"


def main():
    try:
        groups = [("Valid formulas", run_valid()), ("Invalid formulas", run_invalid()),
                  ("Optional evaluation", run_eval())]
    except CompilerError as exc:
        print("ERROR:", exc)
        return 2
    total = failed = 0
    md = ["# Automated test results", "", "Generated by `tests/test_runner.py` from the real compiler executable.", ""]
    for title, results in groups:
        print("\n== %s ==" % title)
        for i, (f, e, a, s, ok) in enumerate(results, 1):
            print("[%s] %2d. %-34s -> %s" % ("PASS" if ok else "FAIL", i, f.replace("\n", "\\n"), a))
            total += 1
            failed += 0 if ok else 1
        md.append(md_table(title, results))
    summary = "%d tests, %d passed, %d failed" % (total, total - failed, failed)
    print("\n" + summary)
    md.append("**%s**\n" % summary)
    with open(os.path.join(ROOT, "docs", "test_results.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(md))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
